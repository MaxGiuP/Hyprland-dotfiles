#!/usr/bin/env python3
"""Apply display settings and atomically save native Hyprland monitor rules."""

import fcntl
import json
import math
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


HEADER = "-- Generated by Quickshell display settings. Do not edit manually.\n"
DATA_PREFIX = "-- Saved layout: "


def validate_rules(rules):
    if not isinstance(rules, list) or not rules:
        raise ValueError("No display settings supplied")
    validated = {}
    for rule in rules:
        if not isinstance(rule, dict):
            raise ValueError("Invalid display settings")
        output = rule.get("output", "")
        mode = rule.get("mode", "")
        position = rule.get("position", "")
        scale = rule.get("scale")
        transform = rule.get("transform")
        if not isinstance(output, str) or not re.fullmatch(r"[A-Za-z0-9_.:-]+", output):
            raise ValueError("Invalid display connector")
        if not isinstance(mode, str) or not re.fullmatch(r"[1-9]\d*x[1-9]\d*@\d+(?:\.\d+)?", mode):
            raise ValueError(f"Invalid mode for {output}")
        if not isinstance(position, str) or not re.fullmatch(r"-?\d+x-?\d+", position):
            raise ValueError(f"Invalid position for {output}")
        if type(scale) not in (int, float) or not math.isfinite(scale) or scale <= 0:
            raise ValueError(f"Invalid scale for {output}")
        if type(transform) is not int or not 0 <= transform <= 7:
            raise ValueError(f"Invalid orientation for {output}")
        if output in validated:
            raise ValueError(f"Duplicate display connector: {output}")
        validated[output] = dict(output=output, mode=mode, position=position,
                                 scale=scale, transform=transform)
    return validated


def monitor_command(rule):
    return (f'hl.monitor({{ output = {json.dumps(rule["output"])}, '
            f'mode = {json.dumps(rule["mode"])}, position = {json.dumps(rule["position"])}, '
            f'scale = {rule["scale"]}, transform = {rule["transform"]} }})')


def render_layout(rules):
    ordered = [rules[name] for name in sorted(rules)]
    return (HEADER + DATA_PREFIX + json.dumps(ordered, separators=(",", ":")) + "\n\n"
            + "\n".join(monitor_command(rule) for rule in ordered) + "\n")


def read_layout(path):
    if not path.exists():
        return {}
    content = path.read_text()
    lines = content.splitlines()
    if not content.startswith(HEADER) or len(lines) < 2 or not lines[1].startswith(DATA_PREFIX):
        raise ValueError(f"Cannot replace unmanaged monitor settings in {path}")
    rules = validate_rules(json.loads(lines[1][len(DATA_PREFIX):]))
    if content != render_layout(rules):
        raise ValueError(f"Monitor settings in {path} were edited manually; refusing to overwrite them")
    return rules


def apply_and_save(path, updates):
    updates = validate_rules(updates)
    path.parent.mkdir(parents=True, exist_ok=True)
    # Lock the directory, which remains stable across atomic file replacements.
    directory_fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
    temporary = None
    try:
        fcntl.flock(directory_fd, fcntl.LOCK_EX)
        saved = read_layout(path)
        saved.update(updates)
        with tempfile.NamedTemporaryFile(mode="w", dir=path.parent,
                                         prefix=".monitor-layout-", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(render_layout(saved))
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), 0o644)
        # Check the compositor reply too: hyprctl can report errors with exit 0.
        result = subprocess.run(
            ["hyprctl", "eval", "\n".join(monitor_command(rule) for rule in updates.values())],
            capture_output=True, text=True, timeout=15, check=False,
        )
        if result.returncode != 0 or result.stdout.strip() != "ok":
            raise RuntimeError(result.stderr.strip() or result.stdout.strip()
                               or "Hyprland rejected the display settings")
        try:
            os.replace(temporary, path)
            os.fsync(directory_fd)
        except OSError as error:
            raise RuntimeError(f"Display settings applied temporarily but could not be saved: {error}") from error
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
        os.close(directory_fd)


def main():
    try:
        config_home = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
        apply_and_save(config_home / "hypr/hyprland/monitor_layout.lua", json.loads(sys.argv[1]))
    except (IndexError, ValueError, OSError, RuntimeError, subprocess.TimeoutExpired) as error:
        print(str(error), file=sys.stderr)
        return 1
    print("ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
